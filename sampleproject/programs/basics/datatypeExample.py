#integer
age=30
print(type(age))
print("Age is:",age)

#float
weight=60.8
print(type(weight))
print("Weight is:",weight)

#string
FirstName='Indira'
LastName="Desai"
print(type(FirstName))
print("First Name is:",FirstName)
print(type(LastName))
print("Last Name is:",LastName)

#Boolean
isStudent=True
print(type(isStudent))
print("Is Student:", isStudent)

#List
list=[10,20,30,40,50]
print(type(list))
print("List is:", list)
list1=[10,30,60.7,"Indira,False"]
print("List can contain different datatypes:",list1)
list2=[100,200,"Apple",[1,2,3],True]
print("list can have sublist:",list2)

#Tuple
tuple=(10,20,30,40,50)
print(type(tuple))
print("tuple is:",tuple)

#set
set={100,200,300,400,500}
print(type(set))
print("set is:",set)

#dictionary
dict={"Name":"Indira","age":30,"weight":60.0}
print(type(dict))
print("dictionary is:",dict)

#none
